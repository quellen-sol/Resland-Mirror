// Per-page SEO metadata and structured data for the public pages.
//
// Next merges metadata shallowly: a page that sets `openGraph` replaces the
// root layout's whole openGraph object, image included. Every public page
// builds its metadata here so its canonical URL, share title and share image
// are its own instead of the home page's.
import type { Metadata } from "next";

export const SITE_URL = "https://resland.org";
export const SITE_NAME = "Resland";
export const SITE_DESCRIPTION =
  "Tailor your software engineering resume to each job posting. Resland asks for the real numbers behind your bullets and never makes anything up.";

/** The share card generated by app/opengraph-image.tsx. */
export const DEFAULT_OG_IMAGE = "/opengraph-image";

export interface PageSeo {
  /** A plain title gets the root layout's " · Resland" suffix; use
   *  `{ absolute }` to set the whole thing. */
  title: string | { absolute: string };
  description: string;
  /** Path from the site root, e.g. "/help". Becomes the canonical URL. */
  path: string;
  type?: "website" | "article";
  /** The page's folder has its own opengraph-image file. Setting an image
   *  here would override it, so leave the image to that file. */
  ownImage?: boolean;
}

export function pageMetadata({
  title,
  description,
  path,
  type = "website",
  ownImage = false,
}: PageSeo): Metadata {
  return {
    title,
    description,
    alternates: { canonical: path },
    // No `twitter` here: Next fills the X card from openGraph when a page
    // doesn't set one, which keeps the two from drifting apart.
    openGraph: {
      type,
      url: path,
      siteName: SITE_NAME,
      title: typeof title === "string" ? `${title} · ${SITE_NAME}` : title.absolute,
      description,
      ...(ownImage ? {} : { images: [DEFAULT_OG_IMAGE] }),
    },
  };
}

export function absoluteUrl(path: string): string {
  return new URL(path, SITE_URL).toString();
}

export interface Crumb {
  name: string;
  path: string;
}

/** schema.org BreadcrumbList for a trail of pages, root first. */
export function breadcrumbJsonLd(crumbs: Crumb[]): Record<string, unknown> {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: crumbs.map((crumb, i) => ({
      "@type": "ListItem",
      position: i + 1,
      name: crumb.name,
      item: absoluteUrl(crumb.path),
    })),
  };
}

/** schema.org FAQPage. Answers must be plain text. */
export function faqJsonLd(faqs: readonly (readonly [string, string])[]): Record<string, unknown> {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: faqs.map(([question, answer]) => ({
      "@type": "Question",
      name: question,
      acceptedAnswer: { "@type": "Answer", text: answer },
    })),
  };
}

/** JSON for a <script type="application/ld+json">, with `<` escaped so the
 *  content can't close the script tag. */
export function jsonLdHtml(data: unknown): string {
  return JSON.stringify(data).replace(/</g, "\\u003c");
}
